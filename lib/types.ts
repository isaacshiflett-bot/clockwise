export type Role = 'worker' | 'manager';
export type EntryStatus = 'open' | 'pending' | 'approved' | 'rejected';
export type User = { id:string; name:string; role:Role; pinHash:string; active:boolean; createdAt:string; department:string };
export type Break = {start:string; end:string|null};
export type Output = {categoryId:string; count:number};
export type TimeEntry = {id:string; userId:string; department:string; clockIn:string; clockOut:string|null; breaks:Break[]; note:string; source:'clock'|'manual'; status:EntryStatus; reviewedBy:string|null; reviewedAt:string|null; reviewComment:string; createdAt:string; updatedAt:string; output:Output[]};
export type TaskCategory = {id:string; name:string; unit:string; active:boolean};
export type CoverageTarget = {dayOfWeek:number; hour:number; headcount:number};
export type Session = {userId:string};
export type AppSettings = {payPeriodAnchor:string; payPeriodWeeks:number};
export type BackupStatus = {lastBackupAt:string|null; needsBackup:boolean};
export type Backup = {schemaVersion:number; users:User[]; entries:TimeEntry[]; categories:TaskCategory[]; targets:CoverageTarget[]; session:Session|null; settings:AppSettings; revision:number; lastBackupRevision:number|null; lastBackupAt:string|null};
export type EntryFilters = {userId?:string; status?:EntryStatus; from?:string; to?:string};
